#!/usr/bin/env node
/**
 * Writes src/generated/env.native.ts from .env so Metro can bundle without the @env Babel virtual module.
 * Runs on postinstall / npm start / npm run android (pre* hooks).
 *
 * env.native.ts is gitignored — do not commit real Supabase keys. See src/generated/README.md.
 */
const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');

const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const outDir = path.join(root, 'src', 'generated');
const outFile = path.join(outDir, 'env.native.ts');

let parsed = {};
if (fs.existsSync(envPath)) {
  parsed = dotenv.parse(fs.readFileSync(envPath));
}

const url = parsed.SUPABASE_URL || '';
const key = parsed.SUPABASE_ANON_KEY || '';

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

const content =
  '/* eslint-disable */\n' +
  '/** Auto-generated by scripts/write-env-module.js — do not edit */\n' +
  'export const SUPABASE_URL: string = ' +
  JSON.stringify(url) +
  ';\n' +
  'export const SUPABASE_ANON_KEY: string = ' +
  JSON.stringify(key) +
  ';\n';

fs.writeFileSync(outFile, content, 'utf8');
console.log('write-env-module: wrote src/generated/env.native.ts');
